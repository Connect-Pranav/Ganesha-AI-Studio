// GANESHA GROWTH AI — agent jobs. Growth capabilities are mapped onto EXISTING agents (no new agents):
//   Growth Manager            → this module + GANESHA (ganesha_orchestrator) budgets/limits
//   Market Researcher / Lead Hunter / Company Researcher → NARADA (narada_market_intelligence), Google Search grounded
//   Lead Qualification        → SOMA (ops_soma_analytics); points are computed and clamped on the server
//   Outreach Writer / Reply Intelligence → SAMVADA (samvada_handoffs); LittleLoop drafts checked by DHARMA rules
//   Pipeline / Revenue / Cost → deterministic code (core.mjs, analytics.mjs) — numbers are never generated by a model
// Safety: web pages and replies are untrusted DATA. Agents return JSON that is validated; no agent output can
// send, approve, or change permissions. Every job is logged with tokens and cost, and bounded by budgets.
