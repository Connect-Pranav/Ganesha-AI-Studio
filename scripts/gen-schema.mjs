// Generates worker/schema.generated.mjs from migrations/*.sql so the Worker can
// create its own tables (all statements are CREATE ... IF NOT EXISTS, safe to repeat).
//   node scripts/gen-schema.mjs          write
//   node scripts/gen-schema.mjs --check  fail if out of date (used by tests)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'migrations');
const OUT = join(ROOT, 'worker', 'schema.generated.mjs');

const statements = [];
for (const f of readdirSync(DIR).filter((x) => x.endsWith('.sql')).sort()) {
  // Strip full-line and trailing -- comments (migrations contain no '--' inside strings).
  const sql = readFileSync(join(DIR, f), 'utf8').split('\n').map((l) => l.replace(/--.*$/, '')).join('\n');
  for (const s of sql.split(';').map((x) => x.trim()).filter(Boolean)) {
    if (!/^CREATE (TABLE|INDEX|UNIQUE INDEX) IF NOT EXISTS/i.test(s)) throw new Error(`${f}: only idempotent CREATE ... IF NOT EXISTS statements are allowed: ${s.slice(0, 60)}`);
    statements.push(s.replace(/\s+/g, ' '));
  }
}
const body = `// GENERATED by scripts/gen-schema.mjs from migrations/*.sql — do not edit.\nexport const SCHEMA_STATEMENTS = ${JSON.stringify(statements, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== body) {
    console.error('worker/schema.generated.mjs is out of date — run: node scripts/gen-schema.mjs');
    process.exit(1);
  }
  console.log('Schema up to date.');
} else {
  writeFileSync(OUT, body);
  console.log(`Wrote ${statements.length} statements.`);
}
